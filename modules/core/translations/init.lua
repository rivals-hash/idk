local loadedModules = {}
local ReverseMap = {}

local function populateReverseMap(mod)
    if not mod then return end
    if mod.Words then
        for engKey, transVal in pairs(mod.Words) do
            ReverseMap[engKey] = engKey
            if type(transVal) == "string" and #transVal > 0 then
                ReverseMap[transVal] = engKey
                local trimmed = transVal:gsub("^%s+", ""):gsub("%s+$", "")
                ReverseMap[trimmed] = engKey
            end
        end
    end
    if mod.Tabs then
        for engKey, transVal in pairs(mod.Tabs) do
            ReverseMap[engKey] = engKey
            if type(transVal) == "string" and #transVal > 0 then
                ReverseMap[transVal] = engKey
                local trimmed = transVal:gsub("^%s+", ""):gsub("%s+$", "")
                ReverseMap[trimmed] = engKey
            end
        end
    end
end

local function resolveLanguageCode(lang)
    if type(lang) == "table" then
        lang = lang[1] or lang.Value or lang.Title
    end
    lang = tostring(lang or "English")
    if LANG_CODES[lang] then return LANG_CODES[lang], lang end
    local lower = string.lower(lang)
    if lower:find("espan") or lower:find("spanish") then
        return "es", "Español"
    elseif lower:find("franc") or lower:find("french") then
        return "fr", "Français"
    elseif lower:find("viet") then
        return "vi", "Tiếng Việt"
    elseif lower:find("portug") then
        return "pt", "Português"
    end
    return "en", "English"
end

local function loadLanguageModule(code)
    if loadedModules[code] then
        return loadedModules[code]
    end

    if BundledLanguages[code] then
        local mod = BundledLanguages[code]
        loadedModules[code] = mod
        populateReverseMap(mod)
        return mod
    end

    local ok, mod = pcall(function()
        local hub = _G.DarlingHub or (getgenv and getgenv().DarlingHub)
        if hub and hub.Require then
            return hub:Require("modules/core/translations/" .. code .. ".lua")
        end
        return nil
    end)

    if not ok or not mod or type(mod) ~= "table" then
        local path = "modules/core/translations/" .. code .. ".lua"
        local okLoad, chunk = pcall(loadfile, path)
        if okLoad and type(chunk) == "function" then
            local okExec, res = pcall(chunk)
            if okExec and type(res) == "table" then
                mod = res
            end
        end
    end

    if not mod or type(mod) ~= "table" then
        mod = { Language = code, Tabs = {}, Words = {} }
    end

    loadedModules[code] = mod
    populateReverseMap(mod)
    return mod
end

