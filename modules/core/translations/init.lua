        return mod and mod.Words or {}
    end
})

local function tr(text, targetLang)
    if not text or type(text) ~= "string" or #text == 0 then
        return text
    end

    local code, canonicalLang = resolveLanguageCode(targetLang or _G.DarlingLanguage or (getgenv and getgenv().DarlingLanguage) or "English")

    local trimmed = text:gsub("^%s+", ""):gsub("%s+$", "")
    local canonical = ReverseMap[trimmed] or ReverseMap[text] or trimmed

    local mod = loadLanguageModule(code)
    if not mod then
        return text
    end

    if mod.Tabs and mod.Tabs[canonical] then
        return mod.Tabs[canonical]
    end
    if mod.Tabs and mod.Tabs[trimmed] then
        return mod.Tabs[trimmed]
    end

    if mod.Words and mod.Words[canonical] then
        return mod.Words[canonical]
    end
    if mod.Words and mod.Words[trimmed] then
        return mod.Words[trimmed]
    end

    return text
end

return {
    LANG_CODES = LANG_CODES,
    TabTranslations = TabTranslations,
    Translations = Translations,
    ReverseMap = ReverseMap,
    loadLanguageModule = loadLanguageModule,
    tr = tr,
}
